#!/usr/bin/env bash
# vm create: download + verify the nano image, build the qcow2 disk, start the VM, seed it, wait for SSH.
# Idempotent: a second run on a running VM does nothing; a partial run is continued.
#
# First configuration (spike result, WP-05 Notes): the boot-time config importer needs a keypress and then
# hangs, so it is skipped; console_run (common.sh) logs in on the serial console, mounts the seed disk (QEMU vvfat of
# disk/seed/, shown as da1) and runs seed.php, which edits /conf/config.xml (root password, SSH key,
# sshd on, LAN = DHCP on the only NIC), then reboots.

IMAGE_FILE() { basename "${IMAGE_URL}"; }

sha256_of() { shasum -a 256 "$1" | awk '{print $1}'; }

# usage: fetch <url> <dest> [sha256]
# Downloads to <dest>.part and renames it when complete. With a known checksum a failed download keeps
# the .part, so the next create resumes it (curl -C -); a .part that already matches is taken as is
# (resuming a complete file fails with HTTP 416). Without a checksum a failed .part is dropped.
fetch() {
  local url="$1" dest="$2" sha="${3:-}"
  [ -s "$dest" ] && return 0
  if [ -n "$sha" ] && [ -s "$dest.part" ] && [ "$(sha256_of "$dest.part")" = "$sha" ]; then
    mv "$dest.part" "$dest"; return 0
  fi
  if [ -s "$dest.part" ]; then log "resuming download $url"; else log "downloading $url"; fi
  local rc=0
  curl -fsS -L -C - --retry 3 -o "$dest.part" "$url" || rc=$?
  if [ "$rc" -eq 33 ]; then
    # the server cannot resume: start over
    log "server does not support resuming; downloading $url from the start"
    rm -f "$dest.part"; rc=0
    curl -fsS -L --retry 3 -o "$dest.part" "$url" || rc=$?
  fi
  if [ "$rc" -ne 0 ]; then
    if [ -n "$sha" ] && [ -s "$dest.part" ] && [ "$(sha256_of "$dest.part")" = "$sha" ]; then
      mv "$dest.part" "$dest"; return 0
    fi
    [ -n "$sha" ] || rm -f "$dest.part"
    die "download failed: $url${sha:+ (partial file kept; run create again to resume)}"
  fi
  mv "$dest.part" "$dest"
}

download_image() {
  mkdir -p "$IMAGES_DIR"
  local name base pub
  name="$(IMAGE_FILE)"
  base="${IMAGE_URL%/*}"
  pub="OPNsense-${OPNSENSE_VERSION}.pub"

  fetch "$IMAGE_URL" "$IMAGES_DIR/$name" "$IMAGE_SHA256"
  if [ "$(sha256_of "$IMAGES_DIR/$name")" != "$IMAGE_SHA256" ]; then
    rm -f "$IMAGES_DIR/$name"
    die "checksum mismatch for $name (expected $IMAGE_SHA256); removed, run create again"
  fi
  fetch "${IMAGE_URL%.bz2}.sig" "$IMAGES_DIR/${name%.bz2}.sig"
  fetch "$base/$pub" "$IMAGES_DIR/$pub"
  if [ "$(sha256_of "$IMAGES_DIR/$pub")" != "$IMAGE_PUBKEY_SHA256" ]; then
    rm -f "$IMAGES_DIR/$pub"
    die "public key $pub does not match the pinned IMAGE_PUBKEY_SHA256"
  fi
}

qemu_img() {
  docker run --rm --entrypoint qemu-img -v "$DISK_DIR:/d" "$QEMU_IMAGE_REF" "$@"
}

build_disk() {
  [ -f "$DISK_DIR/os.qcow2" ] && return 0
  mkdir -p "$DISK_DIR"
  if [ -f "$VM_STATE_DIR/golden.qcow2" ]; then
    log "cloning golden.qcow2"
    cp "$VM_STATE_DIR/golden.qcow2" "$DISK_DIR/os.qcow2.part" && mv "$DISK_DIR/os.qcow2.part" "$DISK_DIR/os.qcow2"
    : > "$DISK_DIR/seeded"
    return 0
  fi
  local name raw sig
  name="$(IMAGE_FILE)"
  raw="$DISK_DIR/${name%.bz2}"
  sig="$IMAGES_DIR/${name%.bz2}.sig"
  [ -s "$sig" ] || die "missing signature file $sig"
  log "decompressing $name"
  bunzip2 -kc "$IMAGES_DIR/$name" > "$raw" || { rm -f "$raw"; die "decompress failed"; }
  log "verifying signature"
  if ! { openssl base64 -d -in "$sig" -out "$raw.sig" \
         && openssl dgst -sha256 -verify "$IMAGES_DIR/OPNsense-${OPNSENSE_VERSION}.pub" -signature "$raw.sig" "$raw" >/dev/null; }; then
    # drop the cached .sig too: a truncated download would otherwise fail every later run
    rm -f "$raw" "$raw.sig" "$sig"
    die "image signature verification failed; removed the signature file, run create again"
  fi
  rm -f "$raw.sig"
  log "building qcow2 disk"
  if ! { qemu_img convert -f raw -O qcow2 "/d/$(basename "$raw")" /d/os.qcow2.part \
         && qemu_img resize /d/os.qcow2.part 16G >/dev/null; }; then
    rm -f "$raw" "$DISK_DIR/os.qcow2.part"
    die "disk conversion failed"
  fi
  mv "$DISK_DIR/os.qcow2.part" "$DISK_DIR/os.qcow2"
  rm -f "$raw"
}

ensure_key() {
  if [ ! -f "$SSH_KEY" ]; then
    mkdir -p "$(dirname "$SSH_KEY")"
    ssh-keygen -q -t ed25519 -N '' -C "vm-test@$VM_NAME" -f "$SSH_KEY"
  fi
}

write_seed() {
  mkdir -p "$DISK_DIR/seed"
  local pub pw
  # both go in base64 so no quoting in PHP or regex replacement syntax ($n backreferences) can bite
  pub="$(base64 < "$SSH_KEY.pub" | tr -d '\n')"
  pw="$(printf '%s' "$ROOT_PASSWORD" | base64 | tr -d '\n')"
  cat > "$DISK_DIR/seed/seed.php" <<SEED
<?php
// First-boot seed, generated by test-vm/vm create.
\$marker = '/conf/.vm-seeded';
if (file_exists(\$marker)) { echo "seed: already applied\n"; exit(0); }
\$f = '/conf/config.xml';
\$x = file_get_contents(\$f);
\$hash = password_hash(base64_decode('$pw'), PASSWORD_BCRYPT);
\$key = '$pub';
\$n = 0;
\$x = preg_replace_callback('#<password>[^<]*</password>#', function (\$m) use (\$hash) { return '<password>' . \$hash . '</password>'; }, \$x, 1, \$c); \$n += \$c;
\$x = preg_replace_callback('#<authorizedkeys/>#', function (\$m) use (\$key) { return '<authorizedkeys>' . \$key . '</authorizedkeys>'; }, \$x, 1, \$c); \$n += \$c;
\$x = preg_replace('#<ssh>\s*<group>admins</group>#', "<ssh>\n      <enabled>enabled</enabled>\n      <group>admins</group>\n      <permitrootlogin>1</permitrootlogin>", \$x, 1, \$c); \$n += \$c;
\$x = preg_replace('#<ipaddr>192\.168\.1\.1</ipaddr>\s*<subnet>24</subnet>#', '<ipaddr>dhcp</ipaddr>', \$x, 1, \$c); \$n += \$c;
if (\$n !== 4) { fwrite(STDERR, "seed: expected 4 edits, made \$n\n"); exit(1); }
file_put_contents(\$f, \$x);
touch(\$marker);
echo "seed: ok\n";
SEED
}

apply_seed() {
  [ -f "$DISK_DIR/seeded" ] && return 0
  log "waiting for the console, then seeding the first configuration (first boot is slow under emulation)"
  console_run 1500 \
    "mkdir -p /mnt && { umount /mnt 2>/dev/null; mount -t msdosfs -o ro /dev/da1s1 /mnt && php /mnt/seed.php && umount /mnt; }" \
    "(nohup sh -c 'sleep 2; reboot' >/dev/null 2>&1 &)" \
    || die "seeding over the serial console failed"
  # give the guest time to go down before the SSH wait, so a not-yet-rebooted guest is not mistaken for ready
  sleep 20
}

cmd_create() {
  [ $# -eq 0 ] || usage_err "usage: vm create"
  die_if_tainted
  require_lock
  local t
  for t in docker curl openssl bunzip2 expect ssh ssh-keygen shasum; do
    command -v "$t" >/dev/null || die "$t not found"
  done
  ensure_state_dir
  # vm never creates symlinks among its entries; never write through one
  check_no_symlinks "$VM_STATE_DIR"
  mkdir -p "$DISK_DIR"

  if container_running && [ -f "$DISK_DIR/seeded" ] && ssh_ready; then
    log "VM ${VM_NAME} is already running and reachable (127.0.0.1:${SSH_PORT})"
    return 0
  fi

  if [ ! -f "$DISK_DIR/os.qcow2" ] && [ ! -f "$VM_STATE_DIR/golden.qcow2" ]; then
    download_image
  fi
  build_disk
  ensure_key
  write_seed

  container_running || compose up -d >&2
  apply_seed
  wait_ssh 1500
  : > "$DISK_DIR/seeded"
  log "VM ${VM_NAME} ready: ssh via 'test-vm/vm ssh', https on 127.0.0.1:${HTTPS_PORT}"
  log "next: 'vm provision'"
}
